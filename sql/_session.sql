BEGIN
  IF UPPER('&&dds_expected_pdb') = 'CHANGE_ME_PDB'
     OR UPPER(l_pdb) <> UPPER('&&dds_expected_pdb')
     OR l_pdb IN ('CDB$ROOT','PDB$SEED') THEN
    RAISE_APPLICATION_ERROR(-20001,'Wrong PDB or config not edited');
  END IF;
END;
