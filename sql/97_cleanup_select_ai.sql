-- Optional AI-only removal. Run as DDS_OWNER before base cleanup.
@@_session.sql
@@_owner.sql
ACCEPT dds_ai_remove CHAR PROMPT 'Type REMOVE_DDS_AI to remove the AI extension: '
BEGIN
  IF NVL('&dds_ai_remove','CANCEL') <> 'REMOVE_DDS_AI' THEN
    RAISE_APPLICATION_ERROR(-20028,'AI cleanup cancelled');
  END IF;
END;
/
UNDEFINE dds_ai_remove
BEGIN
  DBMS_CLOUD_AI_AGENT.DROP_TEAM('DDS_HR_TEAM',TRUE);
  DBMS_CLOUD_AI_AGENT.DROP_TASK('DDS_HR_TASK',TRUE);
  DBMS_CLOUD_AI_AGENT.DROP_AGENT('DDS_HR_AGENT',TRUE);
  DBMS_CLOUD_AI_AGENT.DROP_TOOL('DDS_LIST_TOOL',TRUE);
  DBMS_CLOUD_AI_AGENT.DROP_TOOL('DDS_SUMMARY_TOOL',TRUE);
  DBMS_CLOUD_AI.DROP_PROFILE('DDS_OCI_PROFILE',TRUE);
END;
/
DROP FUNCTION IF EXISTS DDS_OWNER.DDS_LIST_EMPLOYEES;
DROP FUNCTION IF EXISTS DDS_OWNER.DDS_SALARY_SUMMARY;
DROP PACKAGE IF EXISTS DDS_OWNER.DDS_AI_TOOLS;
